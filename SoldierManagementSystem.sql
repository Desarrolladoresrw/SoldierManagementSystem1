-- D2: Create a view showing soldier information.
CREATE VIEW v_soldier_profile AS
SELECT
    s.soldier_id,
    s.first_name || ' ' || s.last_name AS full_name,
    r.rank_name,
    u.unit_name,
    u.location,
    s.status
FROM soldiers s
JOIN ranks r ON s.rank_id = r.rank_id
JOIN units u ON s.unit_id = u.unit_id;


