-- Part C: Queries
-- C1: The last ten soldiers, newest ID first.
SELECT * FROM soldiers ORDER BY soldier_id DESC LIMIT 10;

-- C2: The same ten soldiers, now in ascending ID order.
SELECT * FROM (
    SELECT * FROM soldiers ORDER BY soldier_id DESC LIMIT 10
) AS last_ten
ORDER BY soldier_id ASC;

-- C3: The requested three IDs.
SELECT * FROM soldiers WHERE soldier_id IN (10, 15, 20);

-- C4: P = 9, so the IDs are 19, 24 and 29.
SELECT * FROM soldiers WHERE soldier_id IN (10 + 9, 15 + 9, 20 + 9);

-- C5: Active soldiers between 10 and 20, including both ends.
SELECT * FROM soldiers
WHERE status = 'Active' AND soldier_id BETWEEN 10 AND 20;

-- C6: Highest rank first, then last name.
SELECT s.soldier_id, s.first_name, s.last_name, r.rank_name
FROM soldiers AS s
INNER JOIN ranks AS r ON r.rank_id = s.rank_id
ORDER BY r.rank_level DESC, s.last_name ASC;

-- C7: Active soldiers in unit U = 4.
SELECT s.first_name, s.last_name, r.rank_name, u.unit_name, u.location
FROM soldiers AS s
INNER JOIN ranks AS r ON r.rank_id = s.rank_id
INNER JOIN units AS u ON u.unit_id = s.unit_id
WHERE s.status = 'Active' AND s.unit_id = 4;

-- C8: Everyone assigned to mission M = 5.
SELECT m.mission_name,
       CONCAT(s.first_name, ' ', s.last_name) AS soldier_name,
       sm.mission_role, u.unit_name
FROM soldier_missions AS sm
INNER JOIN missions AS m ON m.mission_id = sm.mission_id
INNER JOIN soldiers AS s ON s.soldier_id = sm.soldier_id
INNER JOIN units AS u ON u.unit_id = s.unit_id
WHERE sm.mission_id = 5;

-- C9: Soldiers with no mission assignment.
SELECT * FROM soldiers AS s WHERE NOT EXISTS (
    SELECT 1
    FROM soldier_missions AS sm
    WHERE sm.soldier_id = s.soldier_id
);

-- C10: Number of soldiers in each unit, largest first.
SELECT u.unit_name, COUNT(s.soldier_id) AS soldier_count FROM units AS u
LEFT JOIN soldiers AS s ON s.unit_id = u.unit_id
GROUP BY u.unit_id, u.unit_name
ORDER BY soldier_count DESC;

