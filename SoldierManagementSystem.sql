-- Part A (Creation of tables: ranks, units, missions, soldiers and soldier missions)
CREATE TABLE ranks (
    rank_id INT PRIMARY KEY,
    rank_name VARCHAR(50) NOT NULL UNIQUE,
    rank_level INT NOT NULL CHECK (rank_level BETWEEN 1 AND 6)
);

CREATE TABLE  units (
    unit_id INT PRIMARY KEY,
    unit_name VARCHAR(100) NOT NULL UNIQUE,
    location VARCHAR(100) NOT NULL
);

CREATE TABLE missions (
    mission_id INT PRIMARY KEY,
    mission_name VARCHAR(40) NOT NULL UNIQUE,
    start_date DATE NOT NULL,
    end_date DATE NULL CHECK(end_date >= start_date)
);

CREATE TABLE soldiers (
    soldier_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_number VARCHAR(30) NOT NULL UNIQUE,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    date_of_birth DATE NOT NULL,
    enlistment_date DATE NOT NULL CHECK (enlistment_date > date_of_birth),
    status VARCHAR(20) NOT NULL DEFAULT 'Active'
    CHECK (status = 'Active' OR status = 'On Leave' OR status = 'Retired'),
    rank_id INT NOT NULL,
    unit_id INT NOT NULL,
    FOREIGN KEY (rank_id) REFERENCES ranks(rank_id),
    FOREIGN KEY (unit_id) REFERENCES units(unit_id)
    
);

CREATE TABLE soldier_missions (
    soldier_id INT NOT NULL,
    mission_id INT NOT NULL,
    mission_role VARCHAR(80) NOT NULL,
    PRIMARY KEY (soldier_id, mission_id),
    FOREIGN KEY (soldier_id) REFERENCES soldiers(soldier_id),
    FOREIGN KEY (mission_id) REFERENCES missions(mission_id)
);

